create table public.safety_app_usage (
  uid text primary key,
  username text not null default '',
  nome text not null default '',
  last_seen timestamptz not null default now(),
  last_access timestamptz,
  sync_state text not null default '',
  pending_data integer not null default 0,
  pending_photos integer not null default 0,
  pending_cloud integer not null default 0,
  pending_errors integer not null default 0,
  client_build text not null default '',
  user_agent text not null default '',
  diagnostics jsonb not null default '[]',
  updated_at timestamptz not null default now()
);
create table public.safety_app_access_events (
  id bigint generated by default as identity primary key,
  uid text not null,
  username text not null default '',
  occurred_at timestamptz not null default now(),
  client_build text not null default '',
  user_agent text not null default ''
);
alter table public.safety_app_usage enable row level security;
alter table public.safety_app_access_events enable row level security;
grant all on public.safety_app_usage, public.safety_app_access_events to service_role;
grant usage, select on all sequences in schema public to service_role;
grant select, insert, update, delete on public.safety_app_usage, public.safety_app_access_events to anon, authenticated;
